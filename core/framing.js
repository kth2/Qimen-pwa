/**
 * 奇门·问句方向(Framing) core —— 纯函数、无副作用、可移植。【Phase 38】
 *
 * 要解决的事：全 app 从来不分「问的是盼着发生的事」还是「怕它发生的事」。
 * 「能否找到」「面试能否成功」与「会不会被抓」「会不会被举报」走的是同一套判读，
 * 而 READING 层的 [助]/[阻] 说的是**此事得成／不成**——对后一类问题，「得成」恰是
 * 求测人最不想要的结果。模型若把 [助] 读成「对你有利」，结论就整个反了。
 *
 * 实测（案例本导出 2026-10-05，396 例／379 回填，逐例人工判读实况）：
 *   · 是非题 199 例里，问「怕发生之事」者 18 例；所怕之事**实际发生的只有 7 例**；
 *   · 这 18 例的解读加权分 0.36，问「盼发生之事」的 181 例为 0.52；
 *   · 错的那几例里，6 例断「会发生」而实际没发生（举报、被抓、投诉、出问题、处分、裁员），
 *     3 例反之——见凶象就断「必发」，是这一类的主错。
 *
 * 本层只做一件事：按问句**字面**检出「所问之事是求测人（或所问之人）不愿其发生的事」。
 *   ① **只认字面，宁漏勿错**。检不出不等于是「盼发生」——只是不加提示，判读照旧。
 *   ② **不改任何判读的极性**。规则库里各条的 [助]/[阻] 一字不动；本层只在证据包里
 *      加一行说明它们在本题里该怎么换算（见 app.js E30），换算由模型按纲要原句做。
 *   ③ **不是纲要**。纲要只写了「时干宫空亡主事虚悬」「用神空亡：所问之事多虚」，
 *      没说过「所问之事」可以是坏事——把这两句用到怕发生之事上，是本层的归纳。
 *
 * 依赖：无。
 */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.Framing = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  var VERSION = '1.0.0';

  // 案例本里有繁体问句（「這次裁員名單裡，有沒有我」）。只折算本层词表用得到的字。
  var TRAD = {
    '會': '会', '沒': '没', '員': '员', '開': '开', '處': '处', '舉': '举', '罰': '罚',
    '題': '题', '傷': '伤', '禍': '祸', '倒': '倒', '閉': '闭', '門': '门', '離': '离',
    '婚': '婚', '單': '单', '裡': '里', '裏': '里', '漏': '漏', '騙': '骗', '盜': '盗',
    '訴': '诉', '報': '报', '審': '审', '獄': '狱', '關': '关', '嗎': '吗', '麼': '么',
    '職': '职', '產': '产', '術': '术', '偷': '偷', '問': '问', '賠': '赔', '虧': '亏'
  };

  // 所问之事若是这些，其「得成」即求测人（或所问之人）受损。
  // 只收**事件**，不收中性的人或机构——「公安局的公务员能考上吗」不该被检出。
  var EVENTS = [
    '被抓', '抓捕', '被捕', '拘留', '拘刑', '刑拘', '拘押', '留置', '坐牢', '入狱', '牢狱', '判刑', '被判',
    '处分', '处罚', '被查', '查处', '举报', '投诉', '告发', '被起诉',
    '罚款', '被罚', '罚单', '抓拍', '扣分', '吊销',
    '裁员', '被裁', '开除', '辞退', '解雇', '降职', '撤职', '免职', '失业',
    '出事', '出问题', '有问题', '大问题', '出意外', '出岔子', '车祸', '受伤', '伤到', '骨折',
    '复发', '恶化', '手术', '动刀', '会死', '漏',
    '倒闭', '关门', '破产', '亏本', '亏钱', '破财', '被骗', '上当', '被盗', '被偷',
    '分手', '离婚', '流产', '报复', '找麻烦'
  ];
  // 机构与「检查」一类只在「会不会有公安/会不会来检查」这种明确问其来不来的句式里算数：
  // 背景里「前阶段去医院检查没有胎心」「公安局的公务员」都不是在问它会不会发生。
  var AGENTS = ['公安', '纪委', '纪检', '监委', '检察', '派出所', '法院', '城管', '税务', '检查', '抽查'];

  function esc(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }
  var EV_RE = EVENTS.map(esc).join('|');
  var AG_RE = AGENTS.map(esc).join('|');
  var STOP = '，。,.；;？?！!\\n';

  // ① 问发生：会不会／是否／有没有／会 …(≤6 字)… 事件或机构
  var P_ASK = new RegExp('(会不会|会否|是否|有没有|有无|会)[^' + STOP + ']{0,6}?(' + EV_RE + '|' + AG_RE + ')');
  // ② 尾问：事件 …(≤4 字)… 吗／了没／与否。
  // 不收「么」（会吃进「什么」）与裸「没有」（会吃进背景句「检查没有胎心」「女友有没有交上」）。
  var P_TAIL = new RegExp('(' + EV_RE + ')[^' + STOP + ']{0,4}?(吗|了没|与否)');
  // ③ 名单句：裁员名单里，有没有我
  var P_LIST = new RegExp('(' + EV_RE + ')[^。.？?！!\\n]{0,8}?(有没有我|有我吗|是不是我|会不会是我)');

  function normalize(q) {
    var s = String(q || '').replace(/\s+/g, '');
    var out = '';
    for (var i = 0; i < s.length; i++) out += TRAD[s.charAt(i)] || s.charAt(i);
    return out;
  }

  /**
   * @param {string} question 用户问句（含背景）
   * @returns {{version:string, direction:'adverse'|'unflagged', event:string, phrase:string, how:string}}
   *   direction 为 'unflagged' 时**不是**「盼发生」的断定，只是本层没有检出。
   */
  function detect(question) {
    var s = normalize(question);
    var res = { version: VERSION, direction: 'unflagged', event: '', phrase: '', how: '' };
    if (!s) return res;
    var m = s.match(P_ASK), how = 'ask';
    if (!m) { m = s.match(P_LIST); how = 'list'; }
    if (!m) { m = s.match(P_TAIL); how = 'tail'; }
    if (!m) return res;
    res.direction = 'adverse';
    res.phrase = m[0];
    res.event = how === 'tail' || how === 'list' ? m[1] : m[2];
    res.how = how;
    return res;
  }

  return { VERSION: VERSION, detect: detect, normalize: normalize, EVENTS: EVENTS, AGENTS: AGENTS };
});
